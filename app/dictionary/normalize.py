"""Підготовка тексту до розпізнавання.

Перш ніж шукати в запиті країни й мови, текст треба звести до єдиного вигляду:
маленькі літери, без апострофів, без зайвих знаків.

Апострофи прибираються навмисно: «В'єтнам» і «Вєтнам» люди пишуть по-різному
(і різними символами апострофа), а для бота це має бути одне й те саме слово.
"""

from __future__ import annotations

import re

# Різні символи апострофа, якими пишуть «В'єтнам»: прямий, типографський,
# зворотний, модифікатор. Усі вони прибираються.
_APOSTROPHES = re.compile(r"['’‘`ʼ´]")

# Слово — це послідовність літер (латиниця або кирилиця) чи цифр.
_WORD = re.compile(r"[0-9a-zа-яёєіїґ]+")

# Доменна зона в тексті: ".de", ".co.uk". Перед крапкою не має бути літери,
# інакше "example.de" сприймалося б як зона в середині слова.
_ZONE = re.compile(r"(?<![0-9a-zа-яёєіїґ])(\.[a-z]{2,6}(?:\.[a-z]{2,6})?)")


def normalize_text(text: str) -> str:
    """Зводить текст до єдиного вигляду: маленькі літери, без апострофів."""
    if not text:
        return ""
    text = _APOSTROPHES.sub("", str(text))
    text = text.replace("ё", "е").lower()
    return re.sub(r"\s+", " ", text).strip()


def tokenize(text: str) -> list[str]:
    """Розбиває нормалізований текст на окремі слова та числа."""
    return _WORD.findall(text)


def find_zone_mentions(text: str) -> list[tuple[str, int, int]]:
    """Знаходить у тексті явні згадки доменних зон: ".de", ".co.uk".

    Повертає список (зона, початок, кінець). Зона з крапкою — завжди
    однозначний сигнал, тому такі згадки безпечні навіть для коротких
    двобуквених зон.
    """
    return [(m.group(1), m.start(1), m.end(1)) for m in _ZONE.finditer(text)]


def mask_span(text: str, start: int, end: int) -> str:
    """Замінює шматок тексту пробілами, зберігаючи довжину рядка.

    Потрібно, щоб після розпізнавання мови той самий шматок тексту вже не
    сприйнявся як назва країни. Приклад: у слові «англійською» ховається
    початок слова «Англія» — але це мова, а не країна.
    """
    return text[:start] + " " * (end - start) + text[end:]
