    """Одна мова з усіма способами її назвати."""

    code: str
    """Короткий код: "de", "en". Усередині бота мова позначається саме так."""

    name_en: str
    """Англійська назва — рівно так, як мова записана в таблиці."""

    name_uk: str
    """Українська назва в називному відмінку: «німецька»."""

    instrumental_uk: str
    """Орудний відмінок: «німецькою». Для рядка «N донорів німецькою мовою»."""

    data_keys: frozenset[str]
    """Як мова може бути записана в таблиці (у нормалізованому вигляді)."""

    synonyms: frozenset[str]
    """Слова-цілком, за якими мову можна впізнати в запиті користувача."""

    stems_uk: tuple[str, ...]
    """Незмінні початки українських слів: «німецьк», «німецькомов»."""

    @property
    def widespread(self) -> bool:
        """Чи «спільна» ця мова — основна для ДВОХ І БІЛЬШЕ країн словника.

        Обчислюється ПРАВИЛОМ зі словника країн, а не хардкодиться списком: щойно
        додається нова країна з цією мовою, мова автоматично стає спільною. Для
        спільних мов мовний крок не входить у підсумок країни (щоб ті самі
        .com-донори не приписувалися кільком країнам одразу).

        Імпорт локальний навмисно: countries.py імпортує languages.py на старті,
        тож зустрічний імпорт можливий лише тут, у момент виклику (без циклу)."""
        from app.dictionary.countries import is_widespread_language

        return is_widespread_language(self.code)


