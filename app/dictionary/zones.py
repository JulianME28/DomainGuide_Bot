"""Глобальні доменні зони — ті, що не належать жодній країні.

Це важливо для чесності підрахунків. Сайт на .com може бути звідки завгодно:
з Британії, з України, з Бразилії. Тому бот НІКОДИ не приписує глобальну зону
якійсь країні — інакше цифри були б вигадані.

Якщо зони немає ні в цьому списку, ні серед країн — вона теж нікому не
приписується. Тобто «нікому не належить» — це поведінка за замовчуванням,
а список нижче потрібен, щоб такі зони можна було гарно показати у звіті.
"""

from __future__ import annotations

GLOBAL_ZONES: frozenset[str] = frozenset(
    {
        # Класичні міжнародні
        ".com",
        ".net",
        ".org",
        ".info",
        ".biz",
        ".pro",
        # Наднаціональні
        ".eu",
        # Нові загальні
        ".online",
        ".site",
        ".shop",
        ".store",
        ".website",
        ".space",
        ".tech",
        ".club",
        ".xyz",
        ".top",
        ".blog",
        ".news",
        ".agency",
        ".digital",
        ".media",
        ".world",
        ".live",
        ".life",
        ".today",
        # Формально це коди країн, але на практиці їх продають усьому світу
        # як загальні. Приписувати їх країні було б помилкою.
        ".co",
        ".io",
        ".me",
        ".tv",
        ".cc",
        ".ai",
        ".app",
        ".dev",
    }
)
"""Зони, які не належать жодній країні."""


def is_global_zone(zone: str) -> bool:
    """Чи ця зона глобальна (нікому не приписується)."""
    return zone.lower() in GLOBAL_ZONES
