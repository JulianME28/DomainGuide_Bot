    @property
    def main_zone(self) -> str:
        """Головна зона — та, яку показуємо в тексті: «.de», «.co.uk»."""
        return self.zones[0] if self.zones else ""

    @property
    def zones_label(self) -> str:
        """Усі зони одним рядком: «.co.uk / .uk»."""
        return " / ".join(self.zones)


