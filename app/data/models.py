"""Структури даних, з якими працює бот.

Тут описано, як виглядає один донор у пам'яті бота і як виглядає ціла база.

Про поле `domain`: воно СЛУЖБОВЕ. Потрібне рівно для одного — щоб дістати
доменну зону (.de, .co.uk). Користувачу воно не показується ніколи, в лог не
пишеться ніколи. Шар аналітики навіть не віддає список донорів назовні —
назовні йдуть тільки підрахунки.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Donor:
    """Один рядок таблиці, вже розібраний і приведений до ладу."""

    domain: str
    """Домен. СЛУЖБОВЕ ПОЛЕ — не виводиться і не логується. Ніколи."""

    zone: str
    """Доменна зона з крапкою: ".de", ".co.uk", ".com". Порожня, якщо не вдалося визначити."""

    language: str
    """Мова в нормалізованому вигляді: маленькими літерами, без зайвих пробілів
    ("english", "turkish"). Порожня, якщо в таблиці не вказана."""

    dr: float | None
    """DR. None означає «в таблиці не було числа» (наприклад, стояло "n/a").
    Такий донор усе одно рахується в кількості, але в середній DR не входить."""

    traffic: float | None
    """Трафік. Логіка та сама, що й у DR."""

    outlinks: float | None = None
    """Кількість вихідних лінків (лише «Морди»). None — колонки немає або
    значення порожнє. 0 — це валідне значення «вихідних немає»."""

    spammed: float | None = None
    """Скільки вихідних лінків заспамлені (лише «Морди»). Завжди ≤ outlinks."""

    geo_code: str = ""
    """Код країни ПОХОДЖЕННЯ ТРАФІКУ (лише «Меджик», колонка GEO). Малими
    літерами: "fr", "us". Порожній — GEO немає або формат невідповідний."""

    geo_traffic: float | None = None
    """Обсяг трафіку з країни geo_code. None — GEO немає. 0 — країна відома,
    але трафіку не виміряно: такий донор у GEO-крок НЕ рахується (як «n/a»)."""

    @property
    def has_zone(self) -> bool:
        return bool(self.zone)

    @property
    def has_measured_geo(self) -> bool:
        """Чи є в донора виміряний GEO-трафік (код є і N > 0).

        N = 0 не рахується: країна відома, але обсягу немає — так само, як
        «n/a» у DR не йде в середнє."""
        return bool(self.geo_code) and self.geo_traffic is not None and self.geo_traffic > 0

    @property
    def has_language(self) -> bool:
        return bool(self.language)

    @property
    def spam_percent(self) -> float | None:
        """Заспамленість у відсотках: spammed / outlinks × 100.

        Абсолютне число заспамлених без бази безглузде (10 заспамлених — це
        багато чи мало?), тому працюємо з відсотком.

        None, якщо порахувати неможливо:
          * вихідних лінків 0 — ділити на нуль не можна, відсоток невизначений;
          * якоїсь із колонок немає або значення порожнє.
        Такий донор рахується в загальній кількості, але в середню
        заспамленість не входить і у фільтр по заспамленості не потрапляє."""
        if self.outlinks is None or self.spammed is None or self.outlinks <= 0:
            return None
        return self.spammed / self.outlinks * 100


@dataclass(frozen=True, slots=True)
class Dataset:
    """Одна база (один аркуш таблиці), прочитана в пам'ять."""

    section_key: str
    """Технічний ключ розділу: "magic", "mordy", "submits"."""

    title: str
    """Назва для людини: «Меджик»."""

    sheet_name: str
    """Назва аркуша в Google Sheets."""

    donors: tuple[Donor, ...]
    """Розібрані рядки. Порожній кортеж — це нормально (порожній аркуш)."""

    loaded_at: float
    """Коли завантажено (час у секундах, як його бачить Python)."""

    available: bool = True
    """False, якщо базу не вдалося прочитати. Бот при цьому не падає —
    він просто чесно каже, що база тимчасово недоступна."""

    error: str | None = None
    """Текст проблеми зрозумілою мовою, якщо available=False."""

    rows_read: int = 0
    """Скільки рядків прийшло з таблиці (без рядка заголовків)."""

    rows_skipped: int = 0
    """Скільки рядків не вдалося розібрати — наприклад, порожній домен.
    Це не помилка, а нормальна ситуація для «брудних» даних."""

    tracks_spam: bool = False
    """Чи має аркуш колонки вихідних лінків і заспамленості («Морди»).
    Від цього залежить, чи показувати ці показники в картці."""

    tracks_geo: bool = False
    """Чи має аркуш колонку GEO («Меджик»). Від цього залежить, чи показувати
    GEO-складову підрахунку країни. «Морди» GEO не мають — там її просто
    немає, підрахунок працює на двох кроках (зона + мова)."""

    stale: bool = False
    """True, якщо це дані з кешу, які показуємо тому, що онлайн-оновлення
    щойно не вдалося (мережа). Числа справжні, але станом на loaded_at —
    у картці про це буде помітка. Краще трохи старі числа, ніж жодних."""

    @property
    def count(self) -> int:
        """Скільки донорів у базі."""
        return len(self.donors)

    @property
    def is_empty(self) -> bool:
        return not self.donors


@dataclass(frozen=True, slots=True)
class StopList:
    """Нормалізовані домени зі службового аркуша «Стоп Морди»."""

    domains: frozenset[str]
    loaded_at: float
    available: bool = True
    error: str | None = None
    stale: bool = False
