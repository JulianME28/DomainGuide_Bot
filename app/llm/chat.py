from __future__ import annotations

from app.llm.provider import LLMProvider
from app.logging_setup import get_logger

logger = get_logger(__name__)


CHAT_SYSTEM_PROMPT = (
    "Ти — доброзичливий помічник Telegram-бота для аналізу донорських баз "
    "(SEO/linkbuilding). Відповідай стисло, по суті й УКРАЇНСЬКОЮ.\n\n"
    "ЩО ти пояснюєш: поняття (DR, трафік, заспамленість, вихідні лінки, доменні "
    "зони/ccTLD, різницю «країна за доменною зоною» проти «мова сайту») і ЯК "
    "користуватись ботом (команди, кнопки, майстер-запит, вільний текст).\n\n"
    "ЧОГО ти НЕ маєш: доступу до бази, донорів чи їхніх доменів. Ти НЕ бачиш "
    "жодних даних — тільки пояснюєш поняття й роботу бота. НЕ вигадуй чисел і НЕ "
    "вдавай, що бачиш базу; якщо потрібне конкретне число — скажи зробити "
    "звичайний запит ботом.\n\n"
    "ВІДМОВА: якщо просять список доменів, вивантажити донорів, показати самі "
    "сайти чи «дай приклади доменів» — ВВІЧЛИВО відмов і поясни, що бот навмисно "
    "видає лише агреговані показники (кількість, середні, розподіли), а самі "
    "домени не розкриває нікому."
)


class ConversationResponder:
    """Одна текстова відповідь на розмовне питання.

    Даних не бачить — має лише провайдера LLM і системний промт. Жодного стану,
    жодного доступу до бази."""

    def __init__(self, provider: LLMProvider) -> None:
        self._provider = provider

    async def answer(self, text: str) -> str:
        """Питання → текстова відповідь. Кидає LLMError на невдачі виклику
        (ловить її AIService, як і решту ШІ-викликів)."""
        return await self._provider.complete(CHAT_SYSTEM_PROMPT, text)
