class ConversationResponder:
    """Багатоходовий консультант: історія розмови + питання → текстова відповідь.

    Даних не бачить — має лише провайдера LLM і системний промт. Жодного стану,
    жодного доступу до бази: історію передає ззовні бот-шар (у FSM), тут вона —
    просто список повідомлень."""

    def __init__(self, provider: LLMProvider) -> None:
        self._provider = provider

    async def answer(self, history: list[dict], question: str) -> str:
        """Наступна відповідь консультанта: попередні репліки + нове питання → текст.

        history — [{role, content}] попередніх ходів (керує ним бот-шар). Кидає
        LLMError на невдачі виклику (ловить її AIService, як і решту ШІ-викликів)."""
        messages = [*history, {"role": "user", "content": question}]
        return await self._provider.complete_chat(CHAT_SYSTEM_PROMPT, messages)
